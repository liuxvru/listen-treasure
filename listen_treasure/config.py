# ---------------------------------------------------------------- 匹配

# 频带加权：把 1kHz 以下的带整体压低一点，再喂给匹配器。
#
# 为什么会有这个东西：游戏背景（BGM、载具、脚步、远处枪声）的能量几乎全在
# 100~800Hz，而拾取音效的主体在 1~8kHz，本机背景最响的 mel 带正好是
# 111/176/223/387/533Hz 那几个。给低频带一点惩罚，理论上能让被掩蔽的音效浮上来。
#
# **默认关闭（BAND_WEIGHT_MIN = 1.0）**，因为两边的证据打平了：
#
#   场景（17 段，数字是召回段数）        不加权   1000Hz/0.70
#   合成背景：真实游戏背景 -6dB            12  →     14      +2
#                                  -9dB    12  →     13      +1
#                                 -12dB    11  →     12      +1
#                                 -15dB    10  →     11      +1
#   白噪 SNR 6dB（bench.py）                16  →     14      -2
#   纯游戏背景误报次数                       1  →      1       0
#   **真实回环录音 cap17.wav（同一段 35.9s）** 9  →      9       0   ← 决定性
#
# 最后一行才是关键：cap17.wav 是本机真实的「游戏在响 + 系统播放 17 段音效」
# 回环录音（音效 -33.5dBFS、背景 -27.5dBFS，即信号比背景小 6dB），合成场景里
# 那 +1~+2 在这段真实录音上**完全没有兑现**。合成背景是 30 秒循环的平稳噪声，
# 真实背景是非平稳的，逐带固定权重吃不到这个便宜。既然真实数据零收益，就不该
# 为它付白噪 -2 的代价，所以默认关掉。留这个开关是因为不同机器的混音风格差别
# 可能很大，需要时把 BAND_WEIGHT_MIN 调到 0.70 即可生效（两侧无需改代码）。
#
# 另一个约束：**不能整片砍掉低频**。早期试过让最低带权重掉到 1/8（相当于把低频
# 信息删光），那样降噪后的残留背景在高频段内容很稀，随机相似度反而升高，
# 纯游戏背景的误报从 1 次涨到 5 次。所以权重有下限。
#
# 权重只施加在**查询侧**（见 dsp.weight_patch）。两侧同时加权的背景收益只多一格
# （-12dB 13 vs 12），但会把白噪场景从 16/17 打到 11/17：模板每行被永久改向之后，
# 白噪里那些"分不高但方向对"的模板被推得更远。所以模板矩阵保持原样。
BAND_WEIGHT_F0_HZ = 1000.0  # 这个频率以下的带开始线性衰减
BAND_WEIGHT_MIN = 1.0  # 权重下限；1.0 = 不加权（默认）。0.70 = 启用

